using System.Security.Cryptography;
using System.Text.RegularExpressions;
using Proctoring.Application.Errors;
using Proctoring.Application.Events;

namespace Proctoring.Infrastructure.Storage;

/// <summary>
/// Audio store on the local file system (AUDIO_STORE_PATH), outside any web root - the API never serves
/// static files, so nothing here is reachable by URL.
///
///   {root}/.staging/{random}.part           uploads in progress / awaiting the database write
///   {root}/{sessionId}/{random 32 hex}.wav  committed audio; the relative path is the storage key
///
/// Every name is generated by the server. Keys are checked against a strict pattern and the resolved path must
/// stay inside the root, so no client input can ever select a file system location.
/// </summary>
public sealed partial class LocalFileAudioStore : IAudioStore
{
    private const string StagingFolder = ".staging";
    private readonly string _root;
    private readonly string _staging;

    [GeneratedRegex("^ses_[A-Za-z0-9]{20,36}/[a-f0-9]{32}\\.wav$")]
    private static partial Regex KeyPattern();

    [GeneratedRegex("^ses_[A-Za-z0-9]{20,36}$")]
    private static partial Regex SessionPattern();

    public LocalFileAudioStore(string rootDirectory)
    {
        _root = Path.GetFullPath(rootDirectory);
        _staging = Path.Combine(_root, StagingFolder);
        Directory.CreateDirectory(_staging);
    }

    public async Task<StagedAudio> StageAsync(Stream content, long maxBytes, CancellationToken ct)
    {
        var path = Path.Combine(_staging, $"{Convert.ToHexStringLower(RandomNumberGenerator.GetBytes(16))}.part");
        try
        {
            using var hash = IncrementalHash.CreateHash(HashAlgorithmName.SHA256);
            long total = 0;
            await using (var file = new FileStream(path, FileMode.CreateNew, FileAccess.Write, FileShare.None, 81920, FileOptions.Asynchronous))
            {
                var buffer = new byte[81920];
                int read;
                while ((read = await content.ReadAsync(buffer, ct)) > 0)
                {
                    total += read;
                    if (total > maxBytes) throw new AudioTooLargeException(maxBytes); // stop reading immediately
                    hash.AppendData(buffer, 0, read);
                    await file.WriteAsync(buffer.AsMemory(0, read), ct);
                }
                await file.FlushAsync(ct);
                file.Flush(flushToDisk: true); // durable before the database row points at it
            }
            return new LocalStagedAudio(path) { SizeBytes = total, Sha256 = Convert.ToHexStringLower(hash.GetHashAndReset()) };
        }
        catch
        {
            TryDelete(path); // aborted, too large, or disk error: no partial file stays behind
            throw;
        }
    }

    public string NewStorageKey(string sessionId)
    {
        if (!SessionPattern().IsMatch(sessionId)) throw new ArgumentException("Invalid session id", nameof(sessionId));
        return $"{sessionId}/{Convert.ToHexStringLower(RandomNumberGenerator.GetBytes(16))}.wav";
    }

    public async Task CommitAsync(StagedAudio staged, string storageKey, CancellationToken ct)
    {
        if (staged is not LocalStagedAudio local) throw new ArgumentException("Staged audio from another store", nameof(staged));
        var target = Resolve(storageKey);
        Directory.CreateDirectory(Path.GetDirectoryName(target)!);
        await FileMoves.MoveAsync(local.Path, target, overwrite: false, ct); // same volume -> atomic rename
        local.MarkCommitted();
    }

    public Task<bool> ExistsAsync(string storageKey, CancellationToken ct) => Task.FromResult(File.Exists(Resolve(storageKey)));

    public Task DeleteAsync(string storageKey, CancellationToken ct)
    {
        var path = Resolve(storageKey);
        if (File.Exists(path)) File.Delete(path);
        var dir = Path.GetDirectoryName(path)!;
        if (Directory.Exists(dir) && !Directory.EnumerateFileSystemEntries(dir).Any()) Directory.Delete(dir);
        return Task.CompletedTask;
    }

    public Uri GetProcessingUri(string storageKey) => new(Resolve(storageKey));

    public Task<int> DeleteStaleStagingAsync(TimeSpan olderThan, CancellationToken ct)
    {
        var cutoff = DateTime.UtcNow - olderThan; // file times are wall-clock times
        var deleted = 0;
        foreach (var file in Directory.EnumerateFiles(_staging, "*.part"))
        {
            if (File.GetLastWriteTimeUtc(file) >= cutoff) continue;
            if (TryDelete(file)) deleted++;
        }
        return Task.FromResult(deleted);
    }

    /// <summary>Storage key -> absolute path, refusing anything that is not a key this store generated.</summary>
    private string Resolve(string storageKey)
    {
        if (!KeyPattern().IsMatch(storageKey)) throw new ArgumentException("Invalid storage key", nameof(storageKey));
        var full = Path.GetFullPath(Path.Combine(_root, storageKey.Replace('/', Path.DirectorySeparatorChar)));
        if (!full.StartsWith(_root + Path.DirectorySeparatorChar, StringComparison.Ordinal))
            throw new ArgumentException("Storage key escapes the audio root", nameof(storageKey));
        return full;
    }

    private static bool TryDelete(string path)
    {
        try
        {
            File.Delete(path);
            return true;
        }
        catch (IOException)
        {
            return false; // still open by an in-flight upload; a later run removes it
        }
        catch (UnauthorizedAccessException)
        {
            return false;
        }
    }

    private sealed class LocalStagedAudio(string path) : StagedAudio
    {
        public string Path { get; } = path;

        public void MarkCommitted() => Committed = true;

        public override Stream OpenRead() =>
            new FileStream(Path, FileMode.Open, FileAccess.Read, FileShare.Read, 4096, FileOptions.Asynchronous);

        public override ValueTask DisposeAsync()
        {
            if (!Committed) TryDelete(Path);
            return ValueTask.CompletedTask;
        }
    }
}
