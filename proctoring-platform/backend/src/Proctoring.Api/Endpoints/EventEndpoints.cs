using System.Text.Json;
using System.Text.Json.Nodes;
using System.Text.RegularExpressions;
using Microsoft.AspNetCore.Http.Features;
using Microsoft.AspNetCore.WebUtilities;
using Microsoft.Extensions.Options;
using Microsoft.Net.Http.Headers;
using Proctoring.Api.Errors;
using Proctoring.Application.Errors;
using Proctoring.Application.Events;
using Proctoring.Contracts.Errors;
using Proctoring.Contracts.Events;

namespace Proctoring.Api.Endpoints;

/// <summary>Audio event routes from docs/contracts/http-api.v1.md.</summary>
public static partial class EventEndpoints
{
    private static readonly string[] AudioContentTypes = ["audio/wav", "audio/x-wav", "audio/wave", "audio/vnd.wave"];
    private const int MaxParts = 4;
    private const long MultipartOverheadBytes = 64 * 1024;

    [GeneratedRegex("^ses_[A-Za-z0-9]{20,}$")]
    private static partial Regex SessionIdPattern();

    public static RouteGroupBuilder MapEventEndpoints(this IEndpointRouteBuilder app)
    {
        var group = app.MapGroup("/api/v1/sessions/{sessionId}/events").WithTags("Events");

        group.MapPost("", UploadAsync)
            .WithName("UploadEvent")
            .WithSummary("Upload one speech event: multipart 'metadata' (JSON) + 'audio' (16 kHz mono 16-bit PCM WAV)")
            .DisableAntiforgery()
            .Produces<EventStatusResponse>(StatusCodes.Status202Accepted)
            .Produces<EventStatusResponse>(StatusCodes.Status200OK)
            .ProducesProblem(StatusCodes.Status400BadRequest)
            .ProducesProblem(StatusCodes.Status401Unauthorized)
            .ProducesProblem(StatusCodes.Status404NotFound)
            .ProducesProblem(StatusCodes.Status409Conflict)
            .ProducesProblem(StatusCodes.Status413PayloadTooLarge)
            .ProducesProblem(StatusCodes.Status415UnsupportedMediaType)
            .ProducesProblem(StatusCodes.Status422UnprocessableEntity)
            .ProducesProblem(StatusCodes.Status503ServiceUnavailable);

        group.MapGet("", ListAsync).WithName("ListEvents").Produces<EventListResponse>();
        group.MapGet("/{eventId}", GetAsync).WithName("GetEvent").Produces<EventStatusResponse>().ProducesProblem(StatusCodes.Status404NotFound);
        group.MapGet("/{eventId}/result", GetResultAsync).WithName("GetEventResult").ProducesProblem(StatusCodes.Status404NotFound);
        return group;
    }

    /// <summary>
    /// Order of checks: credentials (401) -> session and token (404 / 401 expired) -> session still accepts
    /// uploads (409) -> request format (415) -> streamed body (413 / 400 / 422). Nothing is read or stored
    /// before the caller has been authenticated.
    /// </summary>
    private static async Task<IResult> UploadAsync(string sessionId, HttpContext http, AudioEventService events, IAudioStore store,
        IOptions<AudioEventOptions> options, CancellationToken ct)
    {
        var token = BearerToken.Read(http);
        if (!SessionIdPattern().IsMatch(sessionId)) return Problems.NotFound(http);
        var session = await events.AuthorizeUploadAsync(sessionId, token, ct);

        if (!MediaTypeHeaderValue.TryParse(http.Request.ContentType, out var contentType)
            || !contentType.MediaType.Equals("multipart/form-data", StringComparison.OrdinalIgnoreCase))
            throw new UnsupportedMediaTypeException("Content-Type must be multipart/form-data with 'metadata' and 'audio' parts");
        var boundary = HeaderUtilities.RemoveQuotes(contentType.Boundary).Value;
        if (string.IsNullOrWhiteSpace(boundary)) throw new MalformedRequestException("The multipart boundary is missing");

        // Hard cap for the whole request (Kestrel enforces it while streaming).
        var maxAudio = events.MaxAudioBytes;
        if (http.Features.Get<IHttpMaxRequestBodySizeFeature>() is { IsReadOnly: false } size)
            size.MaxRequestBodySize = maxAudio + MultipartOverheadBytes;
        if (http.Request.ContentLength > maxAudio + MultipartOverheadBytes) throw new AudioTooLargeException(maxAudio);

        JsonNode? metadata = null;
        var metadataSeen = false;
        StagedAudio? audio = null;
        try
        {
            var reader = new MultipartReader(boundary, http.Request.Body) { HeadersLengthLimit = 16 * 1024, HeadersCountLimit = 16 };
            var parts = 0;
            while (await ReadSectionAsync(reader, ct) is { } section)
            {
                if (++parts > MaxParts) throw RequestValidationException.For("$", $"At most {MaxParts} parts are allowed");
                // Any client file name is ignored; storage names are generated by the server.
                if (!ContentDispositionHeaderValue.TryParse(section.ContentDisposition, out var disposition)
                    || !disposition.DispositionType.Equals("form-data", StringComparison.OrdinalIgnoreCase))
                    throw new MalformedRequestException("Every part needs 'Content-Disposition: form-data; name=...'");
                var name = HeaderUtilities.RemoveQuotes(disposition.Name).Value;
                switch (name)
                {
                    case "metadata":
                        if (metadataSeen) throw RequestValidationException.For("metadata", "Only one 'metadata' part is allowed");
                        metadataSeen = true;
                        if (!IsContentType(section.ContentType, "application/json"))
                            throw new UnsupportedMediaTypeException("The 'metadata' part must be application/json");
                        var raw = await ReadLimitedAsync(section.Body, options.Value.MaxMetadataBytes, ct)
                                  ?? throw new RequestValidationException(new Dictionary<string, string[]>
                                      { ["metadata"] = [$"must be at most {options.Value.MaxMetadataBytes} bytes"] });
                        try
                        {
                            metadata = JsonNode.Parse(raw);
                        }
                        catch (JsonException)
                        {
                            throw new MalformedRequestException("The 'metadata' part is not valid JSON");
                        }
                        break;
                    case "audio":
                        if (audio is not null) throw RequestValidationException.For("audio", "Only one 'audio' part is allowed");
                        if (!AudioContentTypes.Any(t => IsContentType(section.ContentType, t)))
                            throw new UnsupportedMediaTypeException("The 'audio' part must be audio/wav");
                        audio = await store.StageAsync(section.Body, maxAudio, ct); // 413 as soon as it is too large
                        break;
                    case "video":
                        throw RequestValidationException.For("video", "Video upload is not supported in this version; send audio only");
                    default:
                        throw RequestValidationException.For(string.IsNullOrEmpty(name) ? "$" : name, "Unknown part");
                }
            }

            var missing = new Dictionary<string, string[]>();
            if (!metadataSeen) missing["metadata"] = ["The 'metadata' part is required"];
            if (audio is null) missing["audio"] = ["The 'audio' part is required"];
            if (missing.Count > 0) throw new RequestValidationException(missing);

            var result = await events.UploadAsync(session, metadata, audio!, ct);
            var body = EventMapper.ToResponse(result.Event);
            return result.Outcome switch
            {
                UploadOutcome.Accepted => Results.Json(body, statusCode: StatusCodes.Status202Accepted),
                UploadOutcome.Duplicate => Results.Ok(body),
                _ => QueueUnavailable(http, body),
            };
        }
        finally
        {
            // Deletes the staged file unless it was committed (any failure, abort or validation error).
            if (audio is not null) await audio.DisposeAsync();
        }
    }

    private static async Task<IResult> ListAsync(string sessionId, HttpContext http, AudioEventService events, CancellationToken ct)
    {
        var token = BearerToken.Read(http);
        if (!SessionIdPattern().IsMatch(sessionId)) return Problems.NotFound(http);
        var items = await events.ListAsync(sessionId, token, ct);
        return Results.Ok(new EventListResponse(items.Select(EventMapper.ToResponse).ToList()));
    }

    private static async Task<IResult> GetAsync(string sessionId, string eventId, HttpContext http, AudioEventService events, CancellationToken ct)
    {
        var token = BearerToken.Read(http);
        if (!SessionIdPattern().IsMatch(sessionId)) return Problems.NotFound(http);
        var id = ParseEventId(eventId);
        return Results.Ok(EventMapper.ToResponse(await events.GetAsync(sessionId, token, id, ct)));
    }

    private static async Task<IResult> GetResultAsync(string sessionId, string eventId, HttpContext http, AudioEventService events, CancellationToken ct)
    {
        var token = BearerToken.Read(http);
        if (!SessionIdPattern().IsMatch(sessionId)) return Problems.NotFound(http);
        var e = await events.GetAsync(sessionId, token, ParseEventId(eventId), ct);
        if (e.ResultJson is null) throw new ResultNotAvailableException();
        return Results.Content(e.ResultJson, "application/json");
    }

    /// <summary>503 for an event that was stored (RECEIVED) but could not be queued; it is re-published automatically.</summary>
    private static IResult QueueUnavailable(HttpContext http, EventStatusResponse body)
    {
        http.Response.Headers.RetryAfter = "5";
        var problem = new Microsoft.AspNetCore.Mvc.ProblemDetails
        {
            Type = ProblemTypes.ServiceUnavailable,
            Title = "Processing queue unavailable",
            Status = StatusCodes.Status503ServiceUnavailable,
            Detail = "The event was stored and will be queued automatically. Retrying the same upload returns its current status.",
        };
        problem.Extensions["traceId"] = System.Diagnostics.Activity.Current?.Id ?? http.TraceIdentifier;
        problem.Extensions["correlationId"] = Middleware.CorrelationIdMiddleware.Get(http);
        problem.Extensions["event"] = body;
        return Results.Problem(problem);
    }

    private static Guid ParseEventId(string eventId) =>
        Guid.TryParseExact(eventId, "D", out var id) ? id : throw new EventNotFoundException();

    private static bool IsContentType(string? value, string expected) =>
        MediaTypeHeaderValue.TryParse(value, out var parsed) && parsed.MediaType.Equals(expected, StringComparison.OrdinalIgnoreCase);

    private static async Task<MultipartSection?> ReadSectionAsync(MultipartReader reader, CancellationToken ct)
    {
        try
        {
            return await reader.ReadNextSectionAsync(ct);
        }
        catch (InvalidDataException ex)
        {
            throw new MalformedRequestException($"Malformed multipart body: {ex.Message}");
        }
    }

    private static async Task<byte[]?> ReadLimitedAsync(Stream body, int maxBytes, CancellationToken ct)
    {
        using var buffer = new MemoryStream();
        var chunk = new byte[4096];
        int read;
        while ((read = await body.ReadAsync(chunk, ct)) > 0)
        {
            if (buffer.Length + read > maxBytes) return null;
            buffer.Write(chunk, 0, read);
        }
        return buffer.ToArray();
    }
}
